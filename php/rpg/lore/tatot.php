	<li>Goblinoid members of the species are small, but have plentiful access to mana and are heavily represented as legal mages</li>
	<li>Despite this dimorphism, social roles for Orcs in Dreft are not dictated by their subspecies, though it can determine what jobs/roles a given individual is suitable for</li>
	<li>In Dreft, High Orcs are over represented among trading guilds and merchant clans</li>
	<li>Over represented along the Corsine mountain range and in the large port cities</li>
