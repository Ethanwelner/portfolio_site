<p class="copy">
	Styling itself as the heart of a true liberation movement, Xanthus is an <?php echo sf_lore_link('arks', 'Ark'); ?> in every sense of the word. Originating as a <?php echo sf_lore_link('centafrica', 'Centafrican'); ?> mining colony, its workers conscripted to mine the asteroid <?php echo sf_lore_link('4544-xanthus', '4544 Xanthus'); ?>, it is a nation founded through donations, piracy, and blood. Having served first as a true home for the descendants of the refugee nations, and then as a haven for those escaping oppression under the yoke of the <?php echo sf_lore_link('lunar-industrial-syndicate', 'Lunar Syndicate'); ?> or the <?php echo sf_lore_link('american-empire', 'American Empire'); ?>, Xanthus is a pariah state with few official friends but many supporters.
</p>
<p class="copy">
	Fully self-sufficient, Xanthus spends little time in the Sol System, instead preferring to act as an oasis and crossroads for those escaping poverty or persecution. Its core, an iron asteroid nearly a kilometer wide, provides the perfect material for its never-ending project of colony and station construction. Wherever Xanthus goes, micro-nations appear in its wake. As a model democracy, Xanthus has repeatedly been invited to join the <?php echo sf_lore_link('stellar-democratic-union', 'Stellar Democratic Union'); ?>, at least as an associate member, but the memories aboard Xanthus are long, and it won’t sacrifice its independence for a little comfort.
</p>
