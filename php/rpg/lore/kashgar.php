<p class="copy">
	An outgrowth of humanity’s first deep-space station, laid down nearly two centuries ago, Kashgar is the largest <?php echo sf_lore_link('arks', 'Ark'); ?> in the Settled Systems. This drifting nation forms the heart of the AI diaspora and remains both the birthplace and the spiritual and political anchor of AI culture. Beyond the services it provides to AI Cores, Kashgar is a center of research, media production, and hospitality, wielding considerable soft power and political influence across the Settled Systems. Like all Arks, Kashgar is never stationary, carrying its population alongside a staggering amount of cargo, ships, and passengers from port to port and system to system.
</p>
<p class="copy">
	As the center of the AI world, Kashgar’s presence tends to bring tensions in its wake, and the drifting city is careful never to overstay its welcome. Though heavily defended and well-armored, it has often been the target of human supremacist terrorism. Kashgari security services are considered among the best in the Settled Systems, but their proactive, sometimes trigger-happy approach to protecting the Ark has forced it into more than a few expedited departures. Better to let the blowback occur at a distance than to face it head-on.
</p>
