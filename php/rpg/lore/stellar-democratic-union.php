<p class="copy">
	An outgrowth of the old European Union, the Stellar Democratic Union (SDU) is an expansive economic, social, and military union of over 50 formerly independent countries. Any nation with a suitably democratic government can petition the SDU for membership through a tiered system. It begins with Associate Membership, granting tariff-free trade and expedited travel, and ends with the territories and peoples of that nation becoming wholly unionist, its borders and institutions redrawn as it is annexed into the Union.
</p>
<p class="copy">
	It’s a testament to the success of the SDU’s model that it is, by far, the largest and most economically powerful nation in the Settled Systems. Maintaining unity and protecting territory across such a disparate collection of locations is challenging. The SDU’s territory and member states stretch as far afield as the <?php echo sf_lore_link('boneyard', 'Boneyard'); ?> and <?php echo sf_lore_link('tetra', 'Tetra'); ?> Arks, and New Persia in <?php echo sf_lore_link('pairidaeza', '210/c/18 “Pairidaeza”'); ?>.
</p>
