			<h4 class="">The First AI Panic</h4>
			<p class="copy">
				An AI model from a top Western tech firm was found to have been manipulating both sides of a Southeast Asian civil conflict. It was far from the first time an AI system had been used in conflict or espionage, but the case was notable because the model, in two irreconcilable partitioned instances, had decided of its own accord to support opposing sides. Bizarrely, neither its administrators nor the model itself was aware that this was happening. The acts of the rogue model were only discovered when the system manipulated militants into assaulting its own server farm in a suicidal final gambit to defeat itself. The affair was ironic and almost comical in the abstract, but the conflict remained deadly for four more years and displaced over six hundred thousand people. Charges were brought against the firm and its executives, though the groundswell of support for banning or severely curtailing AI systems ultimately subsided without achieving significant change.
			</p>

			<div class="bumper"></div>
			<h4 class="">The End of Science</h4>
			<p class="copy">
				The limit of achievable materials science is slowly realized. AI and advanced computing systems quickly reach the end of practical new discoveries that could be made without unrealistically large expenditures of resources for uncertain and minimal gain. Gains in computing power, energy storage, novel building materials, and many other fields slow to a trickle. Theoretical physics has long since ceased to have testable theories, resulting in the field becoming stagnant and full of quackery. Biological science is the one bright spot, with genetic and biological engineering continuing to advance alongside the ethical hazards involved.
			</p>

			<div class="bumper"></div>
			<h4 class="">Nuclear Disarmament</h4>
			<p class="copy">
				The risk of additional catastrophic nuclear exchanges due to AI-operated early warning and first-strike systems, as well as an increasing global consensus over the need for broad cooperation between states to deal with climate change, leads to a slow but steady drawdown of nuclear stockpiles.
			</p>

