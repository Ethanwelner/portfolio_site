							<div class="line-container">
								<h5><strong>Requesting Advantage</strong></h5>
								<div class="line"></div>
							</div>
							<ul class="copy">
								<li>A character can request Advantage when they believe they are especially well suited to a task, skill, or role-playing scenario.</li>
								<li>Some Traits will specify a situation where a character can request Advantage that is tied to a specific skill set or physical attribute.</li>
								<li>Requesting Advantage is an expression of both the Stats written on a character sheet and the character's backstory and role-playing attributes.</li>
								<li>Some Kinds, Backgrounds, or Professions will grant the right to request Advantage in a broad set of circumstances, such as a character with a small stature being able to request Advantage when hiding or a professional soldier's ability to request Advantage when learning to wield a new weapon.</li>
								<li>The GM can allow or deny requested Advantage and will determine the appropriate expression of the Advantage.</li>
								<li>Ex. A character with a background as a fisherman may be able to request Advantage, thanks to their past on rocky seas, when they need to keep their balance on an airship in severe turbulence. The GM could choose to give them a +5 Roll Modifier to their Grace Skill Check to stay standing.</li>
								<li>Ex. A pilot is flying the ship they built by hand and know by heart. The GM could choose to give them a bonus to a Skill Check or even waive the need for the Skill Check if the act could be considered routine.</li>
							</ul>
						</div>
					</div>
					<div class="flex-6 content-stack">
						<div class="content-stack content-stack-xs">
							<div class="line-container">
								<h5><strong>Requesting Competence</strong></h5>
								<div class="line"></div>
							</div>
							<p class="copy">A character can request Competence in any situation where they believe other related factors give them enough of a baseline level of capability that they shouldn’t be penalized as harshly, or at all, for lacking a specific skill. The GM can allow or deny requested Competence and decides its outcome, which can range from the character being treated as wholly proficient in the task at hand to being granted a relevant Trait that gives them that skill permanently.</p>
							<ul class="copy">
								<li>A character with expertise in wielding a sword can request Competence when wielding a dagger, even if they don’t have a Trait giving them that skill.</li>
								<li>A bard skilled with a guitar and a bass can likely request Competence with a lute, but the GM may consider the violin a step too far.</li>
							</ul>
							<p class="copy">Many Traits that grant expertise in a skill also grant implied Competence in related Skills.</p>
