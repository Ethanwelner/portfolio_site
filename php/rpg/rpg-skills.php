					<h3>Skill Check Difficulty Ranges</h3>
					<p class="copy">
						Skill Check requirements range from -10 to 80, with an explanation of what those values represent below. Higher checks require higher relevant rolls and modifiers to succeed. A check that notes a Stat can have that Stat added to its total. A complex check that notes multiple Stats must roll separately for each Stat. In general, as actions grow more complex or multi-staged, the relevant Skill Checks will require more Stats to be rolled against at once.
						<br><br>
						Checks at 0 or below are automatically accomplishable even with no skill, and often despite difficulty modifiers to the check. These would only be checked if there was a realistic chance of failure.
					</p>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>-10</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div class="copy">
								Breathing (Endurance)
							</div>
							<div class="copy">
								Being at the top of a tall mountain may give you a -20 difficulty modifier to breathing, giving a character with a poor Endurance Stat a 50/50 chance of passing out.
							</div>
						</div>
					</div>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>0</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div class="copy">
								Reading (Intuition)
							</div>
							<div class="copy">
								If the script is in poor handwriting, it might give the action a -10 difficulty modifier, which gives a character with a poor Intuition Stat a 50/50 chance of not understanding the text.
							</div>
						</div>
					</div>
					<p>
						Checks between 1 and 20 are accomplishable by any character as long as there are no difficulty modifiers. There is a wide gap between a check of 1 and one of 20, though, and while having relevant Stats, Equipment, or Traits may make these checks easy or even automatic, a character not fit for the task may find them almost impossible.
					</p>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>10</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div class="copy">
								Jumping a 6-foot gap (Power)
							</div>
							<div class="copy">
								A character may have an injured leg, giving them a -10 difficulty modifier to the jump.
							</div>
						</div>
					</div>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>20</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div class="copy">
								Making a fire (Mental)
							</div>
							<div class="copy">
								A lighter could give a +15 Roll Modifier to making a fire.
							</div>
						</div>
					</div>
					<p>
						Checks between 21 and 40 are often the difference between requiring novice or expert training, or requiring simple or advanced Equipment. Accomplishable by characters with high Stats, relevant Traits, or Equipment. Many professions have their day-to-day actions in this range. Skill Checks in this range are often still heavily impacted by raw Stat values.
					</p>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>30</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div class="copy">
								Brewing a simple potion (Memory)(Grace)
							</div>
							<div class="copy">
								A potion-brewing Trait could give a +20 Roll Modifier to this Skill Check, turning the impossible into the easy.
							</div>
						</div>
					</div>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>40</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div class="copy">
								Writing a complex computer program (Logic)(Intuition)
							</div>
							<div class="copy">
								A computer use Trait and a computer programming Trait could combine to give a +20 Roll Modifier to this action. Repeated attempts could also allow the character to gain Advantage by slowly fixing the flaws in their program.
							</div>
						</div>
					</div>
					<p>
						Checks between 41 and 60 are often the difference between the daily acts of a master in a profession and something that requires days or weeks of prep time, perfectly attuned Equipment, and external forces acting to make the check succeed. Accomplishable by characters with advanced Traits or high-end Equipment, often both. While Stats may have an impact on the roll, Skill Checks at this level rely more on training and preparation than on talent. Most expert-level tasks fall in this range.
					</p>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>50</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div>
								Disarming a bomb while underwater (Memory)(Grace)(Demeanor)
							</div>
							<div>
								Being in communication with someone reading the defusal manual for the bomb could give significant Advantage to this type of check.
							</div>
						</div>
					</div>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>60</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div>
								Deciphering an alien language (Logic)(Empathy)(Intuition)
							</div>
							<div>
								Having a team of research assistants could give significant Advantage when attempting this type of check, and getting the most out of them may even require several Empathy or Persuasion Skill Checks of their own.
							</div>
						</div>
					</div>
					<p>
						Checks between 61 and 80 are absurdly difficult or are considered impossible by normal means. If a complex task looks like it's in this range, it may be better to break it down into multiple smaller tasks.
					</p>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>70</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div>
								Building a functioning spaceship out of local appliances (Intuition)(Logic)(Memory)(Grace)
							</div>
							<div>
								A check of this nature mostly measures how badly the character fails. A check of this difficulty may actually be accomplishable if the nature of the action allows the character to slowly accrue larger and larger Advantage through many repeated and well-supported attempts.
							</div>
						</div>
					</div>
					<div class="d-flex nowrap align-items-center">
						<div class="d-flex flex-2 nowrap">
							<span class="copy-title"><strong>80</strong></span>
						</div>
						<div class="d-flex flex-16 flex-column flex-gap-4">
							<div>
								Flying by flapping your arms (Power)
							</div>
							<div>
								This is a hyperbolic example, but an 80 should in general be a functionally impossible task. This is the ceiling of what reality can allow.
							</div>
